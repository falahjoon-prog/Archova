// Generates @archova/contracts from packages/contracts/openapi/openapi.yaml (ADR-0002, repo-structure §6):
//   src/generated/openapi.ts     TypeScript types (openapi-typescript), used by api-client
//   src/generated/schemas.ts     zod schemas for every component + operation inputs (server validation, client forms)
//   src/generated/operations.ts  operationId → method, path, module, auth, permission, input schemas
// `--check` fails when the committed output is stale (CI).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import { parse } from 'yaml';

type Schema = {
  $ref?: string;
  type?: string | string[];
  enum?: unknown[];
  format?: string;
  pattern?: string;
  minLength?: number;
  maxLength?: number;
  minimum?: number;
  maximum?: number;
  minItems?: number;
  maxItems?: number;
  minProperties?: number;
  items?: Schema;
  properties?: Record<string, Schema>;
  required?: string[];
  additionalProperties?: boolean | Schema;
  oneOf?: Schema[];
  allOf?: Schema[];
  default?: unknown;
  description?: string;
};
type Parameter = { name: string; in: string; required?: boolean; schema: Schema; $ref?: string };
type Operation = {
  operationId: string;
  parameters?: Parameter[];
  requestBody?: { content: Record<string, { schema: Schema }> };
  'x-module'?: string;
  'x-auth'?: string;
  'x-permission'?: string;
  'x-internal'?: boolean;
  'x-flag'?: string;
};
type Doc = {
  paths: Record<string, Record<string, Operation | Parameter[]>>;
  components: { schemas: Record<string, Schema>; parameters: Record<string, Parameter> };
};

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const pkg = join(root, 'packages/contracts');
const specPath = join(pkg, 'openapi/openapi.yaml');
const outDir = join(pkg, 'src/generated');
const check = process.argv.includes('--check');

const doc = parse(readFileSync(specPath, 'utf8')) as Doc;

const refName = (ref: string) => ref.split('/').pop()!;
const HEADER =
  '// Generated by tools/codegen/generate-contracts.ts from openapi/openapi.yaml. Do not edit.\n';

function zodFor(s: Schema): string {
  if (s.$ref) return `${refName(s.$ref)}Schema`;
  if (s.oneOf) {
    const parts = s.oneOf.map(zodFor);
    return parts.length === 1 ? parts[0]! : `z.union([${parts.join(', ')}])`;
  }
  if (s.allOf) {
    // Composition (`NovaCitation` = `NovaSource` + `quote`): every part must match.
    return s.allOf.map(zodFor).reduce((a, b) => `z.intersection(${a}, ${b})`);
  }
  const types = Array.isArray(s.type) ? s.type : s.type ? [s.type] : [];
  const nullable = types.includes('null') || (s.enum?.includes(null) ?? false);
  const base = types.filter((t) => t !== 'null');
  if (nullable && base.length === 0 && !s.enum) return 'z.null()';
  let out: string;
  if (s.enum) {
    const values = s.enum.filter((v) => v !== null);
    out = `z.enum([${values.map((v) => JSON.stringify(v)).join(', ')}])`;
  } else if (base.length > 1) {
    out = `z.union([${base.map((t) => zodFor({ ...s, type: t })).join(', ')}])`;
  } else {
    const t = base[0];
    switch (t) {
      case 'string': {
        out = 'z.string()';
        if (s.format === 'email') out += '.email()';
        if (s.format === 'date-time') out += '.datetime({ offset: true })';
        if (s.format === 'date') out += '.date()';
        if (s.minLength !== undefined) out += `.min(${s.minLength})`;
        if (s.maxLength !== undefined) out += `.max(${s.maxLength})`;
        if (s.pattern) out += `.regex(new RegExp(${JSON.stringify(s.pattern)}))`;
        break;
      }
      case 'integer':
      case 'number': {
        out = t === 'integer' ? 'z.number().int()' : 'z.number()';
        if (s.minimum !== undefined) out += `.min(${s.minimum})`;
        if (s.maximum !== undefined) out += `.max(${s.maximum})`;
        break;
      }
      case 'boolean':
        out = 'z.boolean()';
        break;
      case 'array': {
        out = `z.array(${s.items ? zodFor(s.items) : 'z.unknown()'})`;
        if (s.minItems !== undefined) out += `.min(${s.minItems})`;
        if (s.maxItems !== undefined) out += `.max(${s.maxItems})`;
        break;
      }
      case 'object':
      case undefined: {
        if (!s.properties && s.additionalProperties && typeof s.additionalProperties === 'object') {
          out = `z.record(z.string(), ${zodFor(s.additionalProperties)})`;
          break;
        }
        if (!s.properties) {
          out = 'z.record(z.string(), z.unknown())';
          break;
        }
        const required = new Set(s.required ?? []);
        const fields = Object.entries(s.properties).map(([k, v]) => {
          const inner = zodFor(v);
          return `  ${JSON.stringify(k)}: ${required.has(k) ? inner : `${inner}.optional()`},`;
        });
        out = `z.object({\n${fields.join('\n')}\n})`;
        if (s.additionalProperties === false) out += '.strict()';
        if (s.minProperties) {
          out += `.refine((v) => Object.keys(v).length >= ${s.minProperties}, { message: 'At least ${s.minProperties} field(s) required' })`;
        }
        break;
      }
      default:
        throw new Error(`Unsupported schema type ${String(t)}`);
    }
  }
  return nullable ? `${out}.nullable()` : out;
}

function deps(s: Schema, acc = new Set<string>()): Set<string> {
  if (s.$ref) acc.add(refName(s.$ref));
  s.oneOf?.forEach((x) => deps(x, acc));
  s.allOf?.forEach((x) => deps(x, acc));
  if (s.items) deps(s.items, acc);
  if (s.properties) Object.values(s.properties).forEach((x) => deps(x, acc));
  if (s.additionalProperties && typeof s.additionalProperties === 'object')
    deps(s.additionalProperties, acc);
  return acc;
}

function sortedSchemaNames(): string[] {
  const schemas = doc.components.schemas;
  const done = new Set<string>();
  const out: string[] = [];
  const visit = (name: string, stack: string[]) => {
    if (done.has(name)) return;
    if (stack.includes(name)) throw new Error(`Schema cycle: ${[...stack, name].join(' → ')}`);
    for (const d of deps(schemas[name]!)) visit(d, [...stack, name]);
    done.add(name);
    out.push(name);
  };
  Object.keys(schemas)
    .sort()
    .forEach((n) => visit(n, []));
  return out;
}

const pascal = (id: string) => id[0]!.toUpperCase() + id.slice(1);

function resolveParam(p: Parameter): Parameter {
  return p.$ref ? doc.components.parameters[refName(p.$ref)]! : p;
}

function paramsObject(params: Parameter[], location: 'path' | 'query'): string | null {
  const ps = params.filter((p) => p.in === location);
  if (ps.length === 0) return null;
  const fields = ps.map((p) => {
    let inner = zodFor(p.schema);
    if (location === 'query' && (p.schema.type === 'integer' || p.schema.type === 'number')) {
      inner = inner.replace(/^z\.number\(\)/, 'z.coerce.number()');
    }
    if (p.schema.default !== undefined) inner += `.default(${JSON.stringify(p.schema.default)})`;
    else if (!p.required) inner += '.optional()';
    return `  ${JSON.stringify(p.name)}: ${inner},`;
  });
  return `z.object({\n${fields.join('\n')}\n})`;
}

async function main() {
  const schemaLines: string[] = [HEADER, "import { z } from 'zod';", ''];
  for (const name of sortedSchemaNames()) {
    schemaLines.push(`export const ${name}Schema = ${zodFor(doc.components.schemas[name]!)};`);
    schemaLines.push(`export type ${name} = z.infer<typeof ${name}Schema>;`, '');
  }

  const opLines: string[] = [
    HEADER,
    "import { z } from 'zod';",
    "import * as s from './schemas';",
    '',
  ];
  const registry: string[] = [];
  const methods = ['get', 'post', 'put', 'patch', 'delete'];
  for (const [path, item] of Object.entries(doc.paths)) {
    const shared = ((item.parameters as Parameter[] | undefined) ?? []).map(resolveParam);
    for (const method of methods) {
      const op = item[method] as Operation | undefined;
      if (!op) continue;
      const params = [...shared, ...(op.parameters ?? []).map(resolveParam)];
      const P = pascal(op.operationId);
      const pathZ = paramsObject(params, 'path');
      const queryZ = paramsObject(params, 'query');
      const content = op.requestBody?.content ?? {};
      const contentType = Object.keys(content)[0] ?? null;
      const bodySchema = contentType ? content[contentType]!.schema : null;
      const qualify = (code: string) => code.replace(/\b(\w+)Schema\b/g, 's.$1Schema');
      if (pathZ) opLines.push(`export const ${P}Params = ${qualify(pathZ)};`);
      if (queryZ) opLines.push(`export const ${P}Query = ${qualify(queryZ)};`);
      if (bodySchema) opLines.push(`export const ${P}Body = ${qualify(zodFor(bodySchema))};`);
      registry.push(
        `  ${op.operationId}: {\n` +
          `    method: '${method.toUpperCase()}',\n` +
          `    path: '${path}',\n` +
          `    module: ${JSON.stringify(op['x-module'] ?? null)},\n` +
          `    auth: ${JSON.stringify(op['x-auth'] ?? 'required')},\n` +
          `    permission: ${JSON.stringify(op['x-permission'] ?? null)},\n` +
          `    internal: ${op['x-internal'] ? 'true' : 'false'},\n` +
          `    flag: ${JSON.stringify(op['x-flag'] ?? null)},\n` +
          `    contentType: ${JSON.stringify(contentType)},\n` +
          `    params: ${pathZ ? `${P}Params` : 'null'},\n` +
          `    query: ${queryZ ? `${P}Query` : 'null'},\n` +
          `    body: ${bodySchema ? `${P}Body` : 'null'},\n` +
          `  },`,
      );
    }
  }
  opLines.push(
    '',
    'export interface OperationDef {',
    "  method: 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE';",
    '  path: string;',
    '  module: string | null;',
    "  auth: 'required' | 'none';",
    '  permission: string | null;',
    '  internal: boolean;',
    '  flag: string | null;',
    '  contentType: string | null;',
    '  params: z.ZodTypeAny | null;',
    '  query: z.ZodTypeAny | null;',
    '  body: z.ZodTypeAny | null;',
    '}',
    '',
    `export const operations = {\n${registry.join('\n')}\n} as const satisfies Record<string, OperationDef>;`,
    '',
    'export type OperationId = keyof typeof operations;',
    '',
  );

  const ast = await openapiTS(new URL(`file://${specPath}`));
  const types = HEADER + astToString(ast);

  const files: Record<string, string> = {
    'schemas.ts': schemaLines.join('\n'),
    'operations.ts': opLines.join('\n'),
    'openapi.ts': types,
  };

  mkdirSync(outDir, { recursive: true });
  const formatted = files;

  if (check) {
    const stale = Object.entries(formatted).filter(([name, content]) => {
      try {
        return readFileSync(join(outDir, name), 'utf8') !== content;
      } catch {
        return true;
      }
    });
    if (stale.length) {
      console.error(
        `Generated contracts are stale: ${stale.map(([n]) => n).join(', ')}. Run \`pnpm gen\`.`,
      );
      process.exit(1);
    }
    console.log('Generated contracts are up to date.');
    return;
  }
  for (const [name, content] of Object.entries(formatted))
    writeFileSync(join(outDir, name), content);
  console.log(`Wrote ${Object.keys(formatted).length} files to ${outDir}`);
}

await main();
