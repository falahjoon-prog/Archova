// pnpm infra:linode-corefile [extra-host ...]: prints the CoreDNS config for the Linode option's allow-list resolver
// (infra/envs/linode-pilot/egress-allowlist.yaml, X25). Only listed hosts resolve; everything else is NXDOMAIN and
// logged. The deploy pipeline passes the managed Postgres hostname as an extra host.
import { readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';
import { checkAllowlist, type Allowlist } from './egress-allowlist';

const HOSTNAME = /^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$/;

export function renderCorefile(list: Allowlist, extraHosts: string[] = []): string {
  const errors = checkAllowlist(list);
  if (errors.length) throw new Error(`egress-allowlist.yaml is invalid:\n${errors.join('\n')}`);
  for (const h of extraHosts)
    if (!HOSTNAME.test(h)) throw new Error(`Not a hostname: ${JSON.stringify(h)}`);
  const hosts = [...new Set([...list.restricted.map((e) => e.host), ...extraHosts])].sort();
  const allowed = hosts
    .map((h) => `${h}:53 {\n  forward . /etc/resolv.conf\n  cache 60\n  errors\n}\n`)
    .join('\n');
  return `# Generated by pnpm infra:linode-corefile from egress-allowlist.yaml. Do not edit.\n\n${allowed}
. {
  log . "blocked {name} {type} from {remote}"
  template ANY ANY {
    rcode NXDOMAIN
  }
}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
  const file = join(root, 'infra/envs/linode-pilot/egress-allowlist.yaml');
  const list = parse(readFileSync(file, 'utf8')) as Allowlist;
  process.stdout.write(renderCorefile(list, process.argv.slice(2)));
}
