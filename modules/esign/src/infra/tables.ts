import {
  boolean,
  integer,
  jsonb,
  numeric,
  pgSchema,
  text,
  timestamp,
  uuid,
} from 'drizzle-orm/pg-core';
import type {
  EnvelopeStatus,
  FieldKind,
  RecipientRole,
  RecipientStatus,
  SourceType,
} from '../domain/envelope';

export const esignSchema = pgSchema('esign');

export const envelopes = esignSchema.table('envelopes', {
  id: uuid('id').primaryKey(),
  orgId: uuid('org_id').notNull(),
  projectId: uuid('project_id').notNull(),
  sourceType: text('source_type').$type<SourceType>(),
  sourceId: uuid('source_id'),
  subject: text('subject').notNull().default(''),
  message: text('message').notNull().default(''),
  status: text('status').$type<EnvelopeStatus>().notNull().default('draft'),
  signingOrder: boolean('signing_order').notNull().default(false),
  allowPaper: boolean('allow_paper').notNull().default(false),
  allowDelegate: boolean('allow_delegate').notNull().default(false),
  expiresDays: integer('expires_days').notNull().default(120),
  reminderDays: integer('reminder_days'),
  expiresAt: timestamp('expires_at', { withTimezone: true }),
  sentAt: timestamp('sent_at', { withTimezone: true }),
  sentBy: uuid('sent_by'),
  completedAt: timestamp('completed_at', { withTimezone: true }),
  voidedAt: timestamp('voided_at', { withTimezone: true }),
  voidReason: text('void_reason'),
  lastRemindedAt: timestamp('last_reminded_at', { withTimezone: true }),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
  createdBy: uuid('created_by'),
  updatedBy: uuid('updated_by'),
  version: integer('version').notNull().default(1),
  deletedAt: timestamp('deleted_at', { withTimezone: true }),
});

export const documents = esignSchema.table('documents', {
  id: uuid('id').primaryKey(),
  orgId: uuid('org_id').notNull(),
  envelopeId: uuid('envelope_id').notNull(),
  fileId: uuid('file_id').notNull(),
  name: text('name').notNull(),
  position: integer('position').notNull().default(0),
  sha256: text('sha256'),
  signedSha256: text('signed_sha256'),
});

export const recipients = esignSchema.table('recipients', {
  id: uuid('id').primaryKey(),
  orgId: uuid('org_id').notNull(),
  envelopeId: uuid('envelope_id').notNull(),
  name: text('name').notNull(),
  email: text('email').notNull(),
  role: text('role').$type<RecipientRole>().notNull().default('needs_to_sign'),
  routingOrder: integer('routing_order').notNull().default(1),
  status: text('status').$type<RecipientStatus>().notNull().default('pending'),
  customSubject: text('custom_subject'),
  customMessage: text('custom_message'),
  language: text('language').notNull().default('en'),
  userId: uuid('user_id'),
  companyId: uuid('company_id'),
  accessLinkId: uuid('access_link_id'),
  copyLinkId: uuid('copy_link_id'),
  sentAt: timestamp('sent_at', { withTimezone: true }),
  viewedAt: timestamp('viewed_at', { withTimezone: true }),
  completedAt: timestamp('completed_at', { withTimezone: true }),
  signedOnPaper: boolean('signed_on_paper').notNull().default(false),
  signatureKind: text('signature_kind').$type<'typed' | 'drawn'>(),
  signatureValue: text('signature_value'),
  signerIp: text('signer_ip'),
  signerUserAgent: text('signer_user_agent'),
  declineReason: text('decline_reason'),
  delegatedFrom: uuid('delegated_from'),
});

export const fields = esignSchema.table('fields', {
  id: uuid('id').primaryKey(),
  orgId: uuid('org_id').notNull(),
  envelopeId: uuid('envelope_id').notNull(),
  documentId: uuid('document_id').notNull(),
  recipientId: uuid('recipient_id').notNull(),
  kind: text('kind').$type<FieldKind>().notNull(),
  page: integer('page').notNull(),
  x: numeric('x', { precision: 6, scale: 5, mode: 'number' }).notNull(),
  y: numeric('y', { precision: 6, scale: 5, mode: 'number' }).notNull(),
  w: numeric('w', { precision: 6, scale: 5, mode: 'number' }).notNull(),
  h: numeric('h', { precision: 6, scale: 5, mode: 'number' }).notNull(),
});

export const events = esignSchema.table('events', {
  id: uuid('id').primaryKey(),
  orgId: uuid('org_id').notNull(),
  envelopeId: uuid('envelope_id').notNull(),
  recipientId: uuid('recipient_id'),
  type: text('type').notNull(),
  at: timestamp('at', { withTimezone: true }).notNull().defaultNow(),
  ip: text('ip'),
  userAgent: text('user_agent'),
  actorUserId: uuid('actor_user_id'),
  data: jsonb('data').$type<Record<string, unknown>>().notNull().default({}),
});
