import {
  boolean,
  date,
  integer,
  jsonb,
  numeric,
  pgSchema,
  real,
  smallint,
  text,
  timestamp,
  uuid,
  bigint,
  primaryKey,
  vector,
} from 'drizzle-orm/pg-core';
import type { ModelTier } from '@archova/ai-prompts';

export const ai = pgSchema('ai');

const audit = {
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
  createdBy: uuid('created_by'),
  updatedBy: uuid('updated_by'),
  version: integer('version').notNull().default(1),
};

export const orgSettings = ai.table('ai_org_settings', {
  orgId: uuid('org_id').primaryKey(),
  aiEnabled: boolean('ai_enabled').notNull().default(true),
  featuresEnabled: text('features_enabled').array(),
  monthlyCreditCap: numeric('monthly_credit_cap', { precision: 12, scale: 2, mode: 'number' }),
  externalAiEnabled: boolean('external_ai_enabled').notNull().default(true),
  retentionDays: integer('retention_days').notNull().default(30),
  ...audit,
});

export type RequestOutcome = 'ok' | 'refused' | 'error' | 'fallback';

export const requests = ai.table('ai_requests', {
  id: uuid('id').notNull(),
  runId: uuid('run_id').notNull(),
  orgId: uuid('org_id').notNull(),
  projectId: uuid('project_id'),
  userId: uuid('user_id'),
  task: text('task').notNull(),
  feature: text('feature').notNull(),
  promptVersion: integer('prompt_version').notNull(),
  provider: text('provider').notNull(),
  model: text('model').notNull(),
  tier: text('tier').$type<ModelTier | 'embedding' | 'ocr'>().notNull(),
  attempt: smallint('attempt').notNull(),
  tokensIn: integer('tokens_in').notNull().default(0),
  tokensOut: integer('tokens_out').notNull().default(0),
  cacheRead: integer('cache_read').notNull().default(0),
  cacheWrite: integer('cache_write').notNull().default(0),
  costMicros: bigint('cost_micros', { mode: 'number' }).notNull().default(0),
  credits: numeric('credits', { precision: 10, scale: 2, mode: 'number' }).notNull().default(0),
  latencyMs: integer('latency_ms').notNull(),
  outcome: text('outcome').$type<RequestOutcome>().notNull(),
  errorKind: text('error_kind'),
  inputRef: text('input_ref'),
  outputRef: text('output_ref'),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
});

export const usageLedger = ai.table('ai_usage_ledger', {
  orgId: uuid('org_id').notNull(),
  day: date('day', { mode: 'string' }).notNull(),
  feature: text('feature').notNull(),
  credits: numeric('credits', { precision: 12, scale: 2, mode: 'number' }).notNull().default(0),
  costMicros: bigint('cost_micros', { mode: 'number' }).notNull().default(0),
  runs: integer('runs').notNull().default(0),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
});

export type SuggestionStatus = 'pending' | 'accepted' | 'edited' | 'rejected';

export const suggestions = ai.table('ai_suggestions', {
  id: uuid('id').primaryKey(),
  orgId: uuid('org_id').notNull(),
  projectId: uuid('project_id'),
  targetType: text('target_type').notNull(),
  targetId: uuid('target_id'),
  task: text('task').notNull(),
  promptVersion: integer('prompt_version').notNull(),
  payload: jsonb('payload').$type<unknown>().notNull(),
  confidence: real('confidence'),
  status: text('status').$type<SuggestionStatus>().notNull().default('pending'),
  runId: uuid('run_id').notNull(),
  decidedBy: uuid('decided_by'),
  decidedAt: timestamp('decided_at', { withTimezone: true }),
  ...audit,
});

export type FeedbackReason = 'wrong' | 'missing' | 'not_useful' | 'wrong_source' | 'other';

export const feedback = ai.table('ai_feedback', {
  id: uuid('id').primaryKey(),
  orgId: uuid('org_id').notNull(),
  runId: uuid('run_id').notNull(),
  userId: uuid('user_id').notNull(),
  rating: smallint('rating').notNull(),
  reason: text('reason').$type<FeedbackReason>(),
  comment: text('comment'),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
});

export type ChunkSourceType = 'document' | 'drawing' | 'induction' | 'rfi' | 'defect';

/** Retrievable text with its embedding (ai/03 §5). `tsv` is generated by Postgres and not mapped. */
export const chunks = ai.table('ai_chunks', {
  id: uuid('id').primaryKey(),
  orgId: uuid('org_id').notNull(),
  projectId: uuid('project_id').notNull(),
  sourceType: text('source_type').$type<ChunkSourceType>().notNull(),
  sourceId: uuid('source_id').notNull(),
  revisionId: uuid('revision_id').notNull(),
  revisionLabel: text('revision_label').notNull(),
  title: text('title').notNull(),
  reference: text('reference'),
  page: integer('page').notNull(),
  chunkIndex: integer('chunk_index').notNull(),
  text: text('text').notNull(),
  embedding: vector('embedding', { dimensions: 1024 }).notNull(),
  embeddingModel: text('embedding_model').notNull(),
  accessScope: text('access_scope').notNull(),
  status: text('status').$type<'current' | 'superseded'>().notNull(),
  pipelineVersion: integer('pipeline_version').notNull(),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
});

export const indexEntries = ai.table(
  'ai_index_entries',
  {
    orgId: uuid('org_id').notNull(),
    projectId: uuid('project_id').notNull(),
    revisionId: uuid('revision_id').notNull(),
    pipelineVersion: integer('pipeline_version').notNull(),
    sourceType: text('source_type').$type<ChunkSourceType>().notNull(),
    sourceId: uuid('source_id').notNull(),
    outcome: text('outcome').$type<'indexed' | 'no_text' | 'unsupported'>().notNull(),
    pages: integer('pages').notNull(),
    chunks: integer('chunks').notNull(),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [primaryKey({ columns: [t.orgId, t.revisionId, t.pipelineVersion] })],
);

/** Cached safety translations (F26, ai/12 §3): one per source version, language, glossary and prompt version. */
export const translations = ai.table('ai_translations', {
  id: uuid('id').primaryKey(),
  orgId: uuid('org_id').notNull(),
  projectId: uuid('project_id'),
  sourceType: text('source_type').$type<'induction_version'>().notNull(),
  sourceId: uuid('source_id').notNull(),
  sourceHash: text('source_hash').notNull(),
  language: text('language').notNull(),
  glossaryVersion: integer('glossary_version').notNull(),
  promptVersion: integer('prompt_version').notNull(),
  payload: jsonb('payload').$type<unknown>().notNull(),
  translationHash: text('translation_hash').notNull(),
  backTranslationScore: real('back_translation_score').notNull(),
  status: text('status').$type<'ready'>().notNull(),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  createdBy: uuid('created_by'),
});

/** F21: a drawing revision pair's text changes and their summary, worded once and shared. */
export const drawingCompares = ai.table('ai_drawing_compares', {
  id: uuid('id').primaryKey(),
  orgId: uuid('org_id').notNull(),
  projectId: uuid('project_id').notNull(),
  revisionId: uuid('revision_id').notNull(),
  againstRevisionId: uuid('against_revision_id').notNull(),
  promptVersion: integer('prompt_version').notNull(),
  payload: jsonb('payload').$type<unknown>().notNull(),
  runId: uuid('run_id'),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  createdBy: uuid('created_by'),
});

/** F21 vision pass: where the linework of a revision pair changed, and Nova's description of each place; shared. */
export const drawingVisualCompares = ai.table('ai_drawing_visual_compares', {
  id: uuid('id').primaryKey(),
  orgId: uuid('org_id').notNull(),
  projectId: uuid('project_id').notNull(),
  revisionId: uuid('revision_id').notNull(),
  againstRevisionId: uuid('against_revision_id').notNull(),
  promptVersion: integer('prompt_version').notNull(),
  payload: jsonb('payload').$type<unknown>().notNull(),
  runId: uuid('run_id'),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  createdBy: uuid('created_by'),
});
